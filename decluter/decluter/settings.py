def _env_bool(name, default=False):
    return os.environ.get(name, str(int(default))).strip().lower() in {
        "1",
        "true",
        "yes",
        "on",
    }


def _env_list(name):
    return [
        value.strip()
        for value in os.environ.get(name, "").split(",")
        if value.strip()
    ]


